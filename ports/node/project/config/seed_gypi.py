#!/usr/bin/env python3
"""从「官方基准」生成我们自己的 config.gypi。

用法：
    python seed_gypi.py <本平台变量环境.json> <输出.gypi> [KEY=JSON_VALUE ...]

**种子从哪来**：`gyp2vcpkg/env/<平台>.json` —— 官方预编译包导出的 `process.config`
（形状 `{variables, target_defaults}`）。

node_js2c 不解析 config.gypi，而是把它**原样嵌进产物**（tools/js2c.cc 的 AddGypi），
所以 config.gypi 的内容就是 `process.config` 的来源，要与官方包对照。标准答案就在官方
二进制里，我们只改**确实随平台/决策变的少数几个**，其余一字不动。

（原来是 `patch-seed.js`，用仓库自带的 node 跑；node 构建搬进 port 后没有 node 可用，
改用 python —— 它本来就是 gyp2vcpkg 那条 python 工具链的一部分。）
"""

import json
import sys


def main(argv):
    if len(argv) < 2:
        sys.stderr.write("用法：seed_gypi.py <变量环境.json> <输出.gypi> [KEY=JSON_VALUE ...]\n")
        return 2
    seed_path, out_path = argv[0], argv[1]
    overrides = argv[2:]

    with open(seed_path, encoding="utf-8") as f:
        seed = json.load(f)

    applied, skipped = [], []
    for pair in overrides:
        if "=" not in pair:
            sys.stderr.write("不认识的覆盖项（要 KEY=JSON）：%s\n" % pair)
            return 2
        key, raw = pair.split("=", 1)
        try:
            value = json.loads(raw)
        except ValueError as err:
            sys.stderr.write("覆盖项 %s 的值不是合法 JSON：%s（%s）\n" % (key, raw, err))
            return 2
        if key in seed.get("variables", {}):
            seed["variables"][key] = value
            applied.append(key)
        else:
            skipped.append(key)

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("# Do not edit. Generated by the configure script.\n")
        f.write(json.dumps(seed, indent=2))
        f.write("\n")

    sys.stderr.write("config.gypi <- %s（%d 个变量）\n" % (seed_path, len(seed.get("variables", {}))))
    if applied:
        sys.stderr.write("  覆盖：%s\n" % ", ".join(applied))
    if skipped:
        sys.stderr.write("  官方基准里没有、未写入：%s\n" % ", ".join(skipped))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))